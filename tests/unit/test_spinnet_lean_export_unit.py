"""Unit tests for spinnet/lean_export.py (prompts/100 step 3.L2): integer tables, literals, generated Lean block."""
import functools
import shutil

import numpy as np
import pytest

from su2plaq.encodings.spinnet import SpinNet
from su2plaq.spinnet import lean_export as LE
from su2plaq.spinnet.walk import FRAME, GENERAL7, classical_slots, coupling_table


@functools.lru_cache(maxsize=None)
def enc():
    return SpinNet()


def test_coupling_ints_match_K():
    c = LE.coupling_ints(enc())
    table = coupling_table(enc())
    codes = [int(x) for x in enc().inner_codes()]
    assert len(c) == 47 and all(isinstance(x, int) for x in c)
    assert np.allclose([x / 2.0 for x in c], [table[k] for k in codes], atol=1e-12, rtol=0)


def test_angle_ints_reproduce_the_walk():
    """sum_r a_r (-1)^{p_r(code)} = 2 * (2K) on every valid inner code (units beta / 2), from the classical slots."""
    a = LE.angle_ints(enc())
    steps, _ = GENERAL7
    assert len(a) == 4 and all(isinstance(x, int) for x in a)
    for code, ck in zip((int(x) for x in enc().inner_codes()), LE.coupling_ints(enc())):
        slots = classical_slots(steps, code, FRAME)
        assert sum(ar * (-1) ** p for ar, p in zip(a, slots)) == 2 * ck


def test_literals_format():
    lit = LE.lean_literals(enc())
    assert set(lit) == {"coupling", "angles", "codes"}
    for key, vals in (("coupling", LE.coupling_ints(enc())), ("angles", LE.angle_ints(enc())),
                      ("codes", [int(x) for x in enc().inner_codes()])):
        assert lit[key] == "[" + ", ".join(str(v) for v in vals) + "]"
    assert lit["codes"].count(",") == 46


def test_non_integer_coupling_raises():
    class Fake:
        def __init__(self):
            self.K_codes = enc().K_codes * 1.01      # 2K no longer integral
        def inner_codes(self):
            return enc().inner_codes()
    with pytest.raises(ValueError):
        LE.coupling_ints(Fake())


def test_write_lean_tables_roundtrip(tmp_path):
    src = LE.CIRCUIT_LEAN
    assert src.exists(), "Circuit.lean missing"
    copy = tmp_path / "Circuit.lean"
    shutil.copy(src, copy)
    text = copy.read_text()
    broken = text.replace(LE.lean_literals(enc())["angles"], "[0, 0, 0, 0]")
    assert broken != text
    copy.write_text(broken)
    assert LE.write_lean_tables(copy) == copy
    assert copy.read_text() == text                      # block regenerated byte for byte
    assert LE.write_lean_tables(copy) == copy and copy.read_text() == text   # idempotent
    # the committed file is up to date (no drift)
    assert src.read_text() == text


def test_write_lean_tables_requires_markers(tmp_path):
    f = tmp_path / "bad.lean"
    f.write_text("namespace X\nend X\n")
    with pytest.raises(ValueError):
        LE.write_lean_tables(f)
    assert f.read_text() == "namespace X\nend X\n"

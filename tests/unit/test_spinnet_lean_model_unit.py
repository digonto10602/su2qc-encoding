"""Audit 100 N4: the hand-readable Lean circuit model in lean/Su2Plaq/SpinNet/Circuit.lean (`frameCx`, `flagOps`, `walkOps`,
tables) must describe the shipped Python circuit `walk.GENERAL7`.  The block is generated by
`lean_export.write_lean_tables`; here the committed file is parsed back (independently of the generator) and re-interpreted
on all 256 data codes, and a drift of GENERAL7 / of the file is shown to fail."""
import re

import pytest

from su2plaq.encodings.spinnet import SpinNet
from su2plaq.spinnet import lean_export as LE
from su2plaq.spinnet.walk import FRAME, GENERAL7, TARGET, classical_slots, coupling_table, mirror

STEPS, _ = GENERAL7
_DEF = r"^def {name} : [^:]*:= (.*)$"
_OP = re.compile(r"\.(x|cx|ccx|rz)((?: \d+)+)")


def _lean_text():
    return LE.CIRCUIT_LEAN.read_text()


def _block(text):
    i, j = text.index("-- BEGIN generated"), text.index("-- END generated")
    return text[i:j]


def _def_rhs(text, name):
    m = re.search(_DEF.format(name=name), _block(text), re.M)
    assert m, f"def {name} not found in the generated block"
    return m.group(1)


def _parse_ops(rhs):
    ops = [(k, tuple(int(a) for a in args.split())) for k, args in _OP.findall(rhs)]
    assert rhs.count(".") == len(ops)            # nothing unparsed
    return ops


def _parse_frame(rhs):
    return tuple((int(a), int(b)) for a, b in re.findall(r"\((\d+), (\d+)\)", rhs))


def _lean_run(init, ops):
    """Python reading of the Lean `step`/`run` (Toffoli semantics for ccx): final state and the rz-wire bits."""
    s, rec = init, []
    for k, a in ops:
        if k == "x":
            s ^= 1 << a[0]
        elif k == "cx":
            s ^= ((s >> a[0]) & 1) << a[1]
        elif k == "ccx":
            if (s >> a[0]) & 1 and (s >> a[1]) & 1:
                s ^= 1 << a[2]
        else:
            rec.append((s >> a[0]) & 1)
    return s, rec


def _lean_start(y, frame):
    for c, t in frame:
        y ^= ((y >> c) & 1) << t
    return (y >> 1) << 1


def test_skeleton_is_compute_walk_mirror():
    compute, walk = LE.split_skeleton()
    assert compute + walk + mirror(compute) == list(STEPS)
    assert all(s[0] != "rz" for s in compute) and sum(s[0] == "rz" for s in walk) == 4
    assert len(compute) == 15 and len(walk) == 10
    assert TARGET == 0 and tuple(FRAME) == ((1, 3), (0, 1), (0, 2))


def test_committed_lean_block_is_current():
    """Circuit.lean's generated block (tables + frameCx + flagOps + walkOps) is exactly what GENERAL7 renders."""
    text = _lean_text()
    assert _block(text) + "-- END generated" == LE._table_block(SpinNet())


def test_lean_ops_parse_back_to_general7():
    """Parsed file text == GENERAL7 compute/walk step by step (rccx <-> ccx, same wires, same order) and FRAME."""
    text = _lean_text()
    compute, walk = LE.split_skeleton()
    rename = {"rccx": "ccx"}
    expect = lambda ss: [(rename.get(s[0], s[0]), tuple(s[1:])) for s in ss]
    assert _parse_ops(_def_rhs(text, "flagOps")) == expect(compute)
    assert _parse_ops(_def_rhs(text, "walkOps")) == expect(walk)
    assert _parse_frame(_def_rhs(text, "frameCx")) == tuple(FRAME)


def test_lean_model_reproduces_python_slots_and_flags_on_all_256_codes():
    text = _lean_text()
    flag, walk = (_parse_ops(_def_rhs(text, n)) for n in ("flagOps", "walkOps"))
    frame = _parse_frame(_def_rhs(text, "frameCx"))
    for y in range(256):
        s, rec = _lean_run(_lean_start(y, frame), flag + walk)
        assert rec == classical_slots(STEPS, y, FRAME), f"slots differ at code {y:08b}"
        F, G1, G2 = ((_lean_run(_lean_start(y, frame), flag)[0] >> w) & 1 for w in (10, 13, 14))
        assert F == (y >> 4 == 0)                                  # bright flag: all corner bits 0
        m = [(_lean_start(y, frame) >> k) & 1 for k in (1, 2, 3)]      # (m1, m2, m3), m1 most significant
        assert G1 == (F and m == [0, 0, 0]) and G2 == (F and m == [1, 0, 0])


def test_lean_walk_phase_equals_twice_coupling_on_valid_codes():
    """The tables and the parsed ops agree: sum_r angle_r (-1)^{slot_r} = 2 * (2K) on the 47 valid inner codes."""
    text = _lean_text()
    enc = SpinNet()
    ang = [int(a) for a in re.findall(r"-?\d+", _def_rhs(text, "angleTable"))]
    cpl = [int(a) for a in re.findall(r"-?\d+", _def_rhs(text, "couplingTable"))]
    codes = [int(a) for a in re.findall(r"\d+", _def_rhs(text, "validInnerCodes"))]
    table = coupling_table(enc)
    assert codes == [int(c) for c in enc.inner_codes()] and len(cpl) == 47
    flag, walk = (_parse_ops(_def_rhs(text, n)) for n in ("flagOps", "walkOps"))
    frame = _parse_frame(_def_rhs(text, "frameCx"))
    for c, k2 in zip(codes, cpl):
        assert k2 == 2 * table[c]
        rec = _lean_run(_lean_start(c, frame), flag + walk)[1]
        assert sum(a if b == 0 else -a for a, b in zip(ang, rec)) == 2 * k2


def test_lean_step_semantics_text_is_pinned():
    """The hand-written (non-generated) interpreter in Circuit.lean keeps the semantics assumed by classical_slots."""
    t = _lean_text()
    for line in ("| .x q => (s.1 ^^^ (1 <<< q), s.2)",
                 "| .cx c t => (cxN s.1 c t, s.2)",
                 "| .ccx a b t => (if bt s.1 a = 1 ∧ bt s.1 b = 1 then s.1 ^^^ (1 <<< t) else s.1, s.2)",
                 "| .rz q => (s.1, s.2 ++ [bt s.1 q])",
                 "def cxN (x c t : Nat) : Nat := x ^^^ (bt x c <<< t)",
                 "def frame (x : Nat) : Nat := frameCx.foldl (fun s p => cxN s p.1 p.2) x",
                 "def start (y : Nat) : Nat := (frame y >>> 1) <<< 1"):
        assert line in t, line


def test_drift_of_general7_changes_the_generated_block(monkeypatch):
    """Rewiring one flag in GENERAL7 (angles unchanged) changes the rendered Lean block, so the stale file fails."""
    steps = [("rccx", 12, 2, 13) if s == ("rccx", 12, 1, 13) else s for s in STEPS]
    assert steps != list(STEPS)
    monkeypatch.setattr(LE, "GENERAL7", (steps, 7))
    assert LE._table_block(SpinNet()) != _block(_lean_text()) + "-- END generated"


def test_hand_edit_of_ops_is_overwritten_and_detected(tmp_path):
    text = _lean_text()
    edited = text.replace(".ccx 12 1 13", ".ccx 12 2 13", 1)
    assert edited != text
    f = tmp_path / "Circuit.lean"
    f.write_text(edited)
    assert _def_rhs(f.read_text(), "flagOps") != _def_rhs(text, "flagOps")
    LE.write_lean_tables(f)
    assert f.read_text() == text


def test_unmodelled_step_is_rejected():
    with pytest.raises(ValueError):
        LE._lean_op(("rc3x", 1, 2, 3, 11))
    with pytest.raises(ValueError):
        LE.split_skeleton([("x", 1), ("rz", 0), ("x", 2)])       # tail is not mirror(compute)

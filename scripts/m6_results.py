# ---------------------------------------------------------------------------------------------------------------- pure helpers
def t_at(table, eps):
    """Value of an {eps: value} table whose keys are floats (1e-6, a fresh metrics dict) or strings ("1e-06", after a JSON round
    trip); None if the table is missing or has no such key."""
    if not table:
        return None
    want = float(eps)
    return next((v for k, v in table.items() if float(k) == want), None)


def rel(path):
    """Repository-relative form of a path under ROOT (as a string); other paths and None are returned as they are."""
    if path is None:
        return None
    try:
        return str(pathlib.Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def lean_word(status) -> str:
    """The Lean column word of a status string (same words as `robust._lean_word`)."""

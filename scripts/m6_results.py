def _det_lean_status(eta: float) -> dict:
    """Lean status of the det layer U_D(eta): `lean_cert.certify_det_layer` on the 16-qubit circuit (prompts/204 section 6.4)."""
    from su2plaq.circuits.rishon import build_UD
    from su2plaq.rishon import lean_cert

    c = lean_cert.certify_det_layer(build_UD(eta), eta)
    return {"status": c.status, "reason": c.reason, "source": f"fresh ({c.seconds:.1f} s)", "cert_path": rel(c.cert_path)}



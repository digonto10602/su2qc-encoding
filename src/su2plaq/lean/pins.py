"""Fingerprints that pin the exporter's exact data inside the Lean checker (`lean/Su2PlaqCert/Pins.lean`).

The checker recomputes SHA-256 of a canonical text of the certificate's 433 states and of its target (at the target's own base)
and compares it with the constants written here from the exporter's exact basis / targets (`exact.py`, themselves
cross-checked against the float code and, in step 2.L6, against the Gauss law and the structure certificate).  A certificate
with other states or another target is therefore rejected by the Lean checker alone, also inside a `native_decide` theorem.

    PYTHONPATH=src python -m su2plaq.lean.pins            # (re)write lean/Su2PlaqCert/Pins.lean
"""
from __future__ import annotations

import hashlib
import pathlib

from su2plaq.lean import exact as E

PINS_FILE = pathlib.Path(__file__).resolve().parents[3] / "lean" / "Su2PlaqCert" / "Pins.lean"
TARGETS = (("UE", 1), ("UB", 1), ("step", 1), ("step", 2))


def _q(x) -> str:
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


def _k(k: E.KNum) -> str:
    return ",".join(_q(c) for c in k.comps())


def states_text(states: list[dict]) -> str:
    """Canonical text: `S<k>:<code>:<a,b,c,d,e,f,g,h>` per term, states in order, terms by code."""
    out = []
    for k, st in enumerate(states):
        for code, a in sorted(zip((int(c) for c in st["codes"]), st["amps"]), key=lambda t: t[0]):
            out.append(f"S{k}:{code}:{_k(a)}\n")
    return "".join(out)


def target_text(blocks: list[dict]) -> str:
    """Canonical text of `exact_target_blocks` output: `B<ks>` per block, `E<i>,<j>:(<ma>,<mb>)=<K>;...` per entry."""
    out = []
    for b in blocks:
        out.append("B" + ",".join(str(k) for k in b["ks"]) + "\n")
        for i, j, lp in sorted(b["entries"], key=lambda t: (t[0], t[1])):
            terms = ";".join(f"({ma},{mb})={_k(v)}" for (ma, mb), v in sorted(lp.items()))
            out.append(f"E{i},{j}:{terms}\n")
    return "".join(out)


def sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def compute_pins(enc=None) -> dict:
    if enc is None:
        from su2plaq.encodings.twelve import TwelveQubit

        enc = TwelveQubit()
    return {"states": sha(states_text(E.exact_encoded_states(enc))),
            "targets": {f"{kind}:{order}": sha(target_text(E.exact_target_blocks(kind, order))) for kind, order in TARGETS}}


def render_lean(p: dict) -> str:
    t = p["targets"]
    return f'''/-!
# Su2PlaqCert.Pins — fingerprints of the exporter's exact data (GENERATED by `python -m su2plaq.lean.pins`; do not edit)

SHA-256 of the canonical text of the 433 exact physical states (data|outer integer, Paulo codes) and of the exact targets of
U_E, U_B and the step (orders 1, 2) at their own base.  See `Su2PlaqCert.Check.Cert.pinError`.
-/
namespace Su2PlaqCert.Pins

def statesSha256 : String := "{p["states"]}"

/-- `(d_alpha, d_beta)` of the exact targets. -/
def targetBase (kind : String) (order : Nat) : Option (Nat × Nat) :=
  match kind, order with
  | "UE", _ => some (4, 2)
  | "UB", _ => some (4, 2)
  | "step", 1 => some (4, 2)
  | "step", 2 => some (8, 2)
  | _, _ => none

def targetSha256 (kind : String) (order : Nat) : Option String :=
  match kind, order with
  | "UE", _ => some "{t["UE:1"]}"
  | "UB", _ => some "{t["UB:1"]}"
  | "step", 1 => some "{t["step:1"]}"
  | "step", 2 => some "{t["step:2"]}"
  | _, _ => none

end Su2PlaqCert.Pins
'''


def write_pins(path=PINS_FILE) -> pathlib.Path:
    path = pathlib.Path(path)
    path.write_text(render_lean(compute_pins()))
    return path


if __name__ == "__main__":
    print(write_pins())
